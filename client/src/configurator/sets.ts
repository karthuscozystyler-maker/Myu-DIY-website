export function getSetsForSeries(series: Series): PresetSet[] {
  return PRESET_SETS.filter(set => set.series === series);
}

export function getSetById(id: string): PresetSet | undefined {
  return PRESET_SETS.find(set => set.id === id);
}

export function getSetVariant(
  preset: PresetSet,
  patternName: string
): SetVariant | undefined {
  const matches = preset.variants?.filter(
    variant => variant.patternName === patternName && variant.sku.trim()
  );
  return matches?.length === 1 ? matches[0] : undefined;
}

