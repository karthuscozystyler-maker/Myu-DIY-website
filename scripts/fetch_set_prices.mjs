// Refreshes client/src/configurator/set-prices.ts from the owner's
// "Myu New Product" Google Sheet (series set tabs, shared by link).
// Only each set variant's SKU, 原價 and 特價 are copied: the sheet's cost and
// margin columns never reach the website.
//
//   node scripts/fetch_set_prices.mjs
import fs from "node:fs";
import path from "node:path";

const SHEET = "1-OUi80F5pBehLdkFlzLH7lsuPx4qgLeXRdMluSvfNqM";
const TABS = { "4 廚房Set": 107, "5 浴室Set": 109, "6 玄關Set": 110, "7 書檯化妝檯Set": 111 };
const out = path.resolve(import.meta.dirname, "../client/src/configurator/set-prices.ts");

function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') (field += '"'), i++;
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") row.push(field), (field = "");
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field), rows.push(row), (row = []), (field = "");
    } else field += c;
  }
  if (field || row.length) row.push(field), rows.push(row);
  return rows;
}

const prices = {};
for (const [tab, gid] of Object.entries(TABS)) {
  const response = await fetch(`https://docs.google.com/spreadsheets/d/${SHEET}/export?format=csv&gid=${gid}`);
  if (!response.ok) throw new Error(`${tab}: HTTP ${response.status}`);
  const [header, ...rows] = parseCsv(await response.text());
  const col = name => {
    const index = header.indexOf(name);
    if (index < 0) throw new Error(`${tab}: no ${name} column`);
    return index;
  };
  const [sku, original, sale] = [col("SKU"), col("原價"), col("特價")];
  for (const row of rows) {
    if (!row[sku]?.trim()) continue;
    const pair = [Number(row[original]), Number(row[sale])];
    if (!pair.every(n => Number.isInteger(n) && n > 0))
      throw new Error(`${tab}: bad price for ${row[sku]}`);
    if (prices[row[sku]]) throw new Error(`Duplicate SKU ${row[sku]}`);
    prices[row[sku].trim()] = pair;
  }
}

const lines = Object.entries(prices)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([sku, [original, sale]]) => `  "${sku}": [${original}, ${sale}],`);
fs.writeFileSync(
  out,
  `/* Generated by scripts/fetch_set_prices.mjs from the "Myu New Product" sheet.
 * Set variant SKU -> [原價, 特價] in HKD. Do not edit by hand. */
export const SET_PRICES: Readonly<Record<string, readonly [number, number]>> = {
${lines.join("\n")}
};
`
);
console.log(`Wrote ${lines.length} set prices to ${path.relative(process.cwd(), out)}`);
